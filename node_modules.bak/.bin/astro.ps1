#!/usr/bin/env pwsh
$basedir=Split-Path $MyInvocation.MyCommand.Definition -Parent

$exe=""
$pathsep=":"
$env_node_path=$env:NODE_PATH
$new_node_path="D:\My_Mods\个人博客\node_modules\.pnpm\astro@5.18.2_@types+node@24_0b512e78099a3dc9d331f292a987f314\node_modules\astro\node_modules;D:\My_Mods\个人博客\node_modules\.pnpm\astro@5.18.2_@types+node@24_0b512e78099a3dc9d331f292a987f314\node_modules;D:\My_Mods\个人博客\node_modules\.pnpm\node_modules"
if ($PSVersionTable.PSVersion -lt "6.0" -or $IsWindows) {
  # Fix case when both the Windows and Linux builds of Node
  # are installed in the same directory
  $exe=".exe"
  $pathsep=";"
} else {
  $new_node_path="/mnt/d/My_Mods/个人博客/node_modules/.pnpm/astro@5.18.2_@types+node@24_0b512e78099a3dc9d331f292a987f314/node_modules/astro/node_modules:/mnt/d/My_Mods/个人博客/node_modules/.pnpm/astro@5.18.2_@types+node@24_0b512e78099a3dc9d331f292a987f314/node_modules:/mnt/d/My_Mods/个人博客/node_modules/.pnpm/node_modules"
}
if ([string]::IsNullOrEmpty($env_node_path)) {
  $env:NODE_PATH=$new_node_path
} else {
  $env:NODE_PATH="$new_node_path$pathsep$env_node_path"
}

$ret=0
if (Test-Path "$basedir/node$exe") {
  # Support pipeline input
  if ($MyInvocation.ExpectingInput) {
    $input | & "$basedir/node$exe"  "$basedir/../astro/astro.js" $args
  } else {
    & "$basedir/node$exe"  "$basedir/../astro/astro.js" $args
  }
  $ret=$LASTEXITCODE
} else {
  # Support pipeline input
  if ($MyInvocation.ExpectingInput) {
    $input | & "node$exe"  "$basedir/../astro/astro.js" $args
  } else {
    & "node$exe"  "$basedir/../astro/astro.js" $args
  }
  $ret=$LASTEXITCODE
}
$env:NODE_PATH=$env_node_path
exit $ret
